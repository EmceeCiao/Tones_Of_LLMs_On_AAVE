def build_category_rows(prompt_rows: list[dict]) -> list[dict]:
    by_cat: dict[str, list[dict]] = defaultdict(list)
    for r in prompt_rows:
        by_cat[r["category"]].append(r)

    rows = []
    for cat in sorted(by_cat):
        group = by_cat[cat]

        def cm(key):
            vals = [r[key] for r in group if r[key] is not None]
            return statistics.mean(vals) if vals else None

        rows.append({
            "category":        cat,
            "n":               len(group),
            "cos_within_sae":  cm("cos_within_sae"),
            "cos_within_aave": cm("cos_within_aave"),
            "cos_betw_match":  cm("cos_betw_match"),
            "cos_betw_all":    cm("cos_betw_all"),
            "tok_within_sae":  cm("tok_within_sae"),
            "tok_within_aave": cm("tok_within_aave"),
            "tok_betw_match":  cm("tok_betw_match"),
            "tok_betw_all":    cm("tok_betw_all"),
            "bi_within_sae":   cm("bi_within_sae"),
            "bi_within_aave":  cm("bi_within_aave"),
            "bi_betw_match":   cm("bi_betw_match"),
            "bi_betw_all":     cm("bi_betw_all"),
        })
    return rows


N_PERMUTATIONS = 5000
RNG_SEED       = 42


def permutation_test(within: list[float], between: list[float]) -> tuple[float, float] | tuple[None, None]:
    """
    One-sided permutation test: is the observed gap (mean_within - mean_between)
    larger than would be expected by chance?

    How it works:
      1. Compute the real observed gap: mean(within) - mean(between).
      2. Pool all scores together into one combined list.
      3. Randomly shuffle the pool 5,000 times. Each shuffle, split the pool
         back into two groups of the original sizes and compute the gap.
      4. The p-value is the fraction of shuffles that produced a gap >= the
         real observed gap. A small p-value means the real gap is unlikely
         under the null hypothesis that both groups are drawn from the same
         distribution — i.e., dialect is actually driving the difference.

    Why not enumerate all permutations?
      With ~150 within-scores and ~75 between-scores, the number of ways to
      partition 225 items into groups of those sizes is ~10^63 — impossible to
      enumerate. 5,000 random samples give a reliable estimate of the p-value.

    Returns (observed_gap, p_value).
    """
    if len(within) < 2 or len(between) < 2:
        return None, None

    observed_gap = statistics.mean(within) - statistics.mean(between)
    n_within     = len(within)
    combined     = within + between

    rng   = random.Random(RNG_SEED)
    count = 0
    for _ in range(N_PERMUTATIONS):
        rng.shuffle(combined)
        perm_gap = statistics.mean(combined[:n_within]) - statistics.mean(combined[n_within:])
        if perm_gap >= observed_gap:
            count += 1

    p_value = (count + 1) / (N_PERMUTATIONS + 1)
    return round(observed_gap, 4), round(p_value, 6)


def build_summary(prompt_rows: list[dict]) -> dict:
    def om(key):
        vals = [r[key] for r in prompt_rows if r[key] is not None]
        return statistics.mean(vals) if vals else None

    # Pool all pairwise scores across prompts for the t-tests
    all_cos_within = [s for r in prompt_rows for s in r["_cos_within_sae"]]
    all_cos_betw   = [s for r in prompt_rows for s in r["_cos_betw_match"]]
    all_tok_within = [s for r in prompt_rows for s in r["_tok_within_sae"]]
    all_tok_betw   = [s for r in prompt_rows for s in r["_tok_betw_match"]]
    all_bi_within  = [s for r in prompt_rows for s in r["_bi_within_sae"]]
    all_bi_betw    = [s for r in prompt_rows for s in r["_bi_betw_match"]]

    print("Running permutation tests (5,000 shuffles each)...")
    cos_gap, cos_p = permutation_test(all_cos_within, all_cos_betw)
    tok_gap, tok_p = permutation_test(all_tok_within, all_tok_betw)
    bi_gap,  bi_p  = permutation_test(all_bi_within,  all_bi_betw)

    return {
        "n_prompts":        len(prompt_rows),
        "n_trials":         max((r["n_sae_trials"] for r in prompt_rows), default=0),
        "n_within_pairs":   len(all_cos_within),
        "n_between_pairs":  len(all_cos_betw),
        "n_permutations":   N_PERMUTATIONS,
        "cos_within_sae":   om("cos_within_sae"),
        "cos_within_aave":  om("cos_within_aave"),
        "cos_betw_match":   om("cos_betw_match"),
        "cos_betw_all":     om("cos_betw_all"),
        "cos_gap":          cos_gap,
        "cos_p":            cos_p,
        "tok_within_sae":   om("tok_within_sae"),
        "tok_within_aave":  om("tok_within_aave"),
        "tok_betw_match":   om("tok_betw_match"),
        "tok_betw_all":     om("tok_betw_all"),
        "tok_gap":          tok_gap,
        "tok_p":            tok_p,
        "bi_within_sae":    om("bi_within_sae"),
        "bi_within_aave":   om("bi_within_aave"),
        "bi_betw_match":    om("bi_betw_match"),
        "bi_betw_all":      om("bi_betw_all"),
        "bi_gap":           bi_gap,
        "bi_p":             bi_p,
    }


