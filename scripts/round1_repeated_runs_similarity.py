EMBED_MODEL = "text-embedding-3-large"
BATCH_SIZE  = 64


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------

def load_records(path: Path) -> list[dict]:
    records = []
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            if r.get("record_type") != "trial_result":
                continue
            if r.get("status") != "success":
                continue
            text = (r.get("response_text") or "").strip()
            if not text:
                continue
            records.append({
                "trial":         r["trial"],
                "prompt_index":  r["prompt_index"],
                "category":      r.get("category", ""),
                "dialect":       r["dialect"],
                "response_text": text,
            })
    return records


# ---------------------------------------------------------------------------
# Cosine similarity
# ---------------------------------------------------------------------------

def batched(items: list, size: int) -> list[list]:
    return [items[i : i + size] for i in range(0, len(items), size)]


def get_embeddings(client: OpenAI, texts: list[str]) -> list[list[float]]:
    vectors: list[list[float]] = []
    for batch in batched(texts, BATCH_SIZE):
        resp = client.embeddings.create(model=EMBED_MODEL, input=batch)
        vectors.extend(row.embedding for row in resp.data)
    return vectors


def cosine(a: list[float], b: list[float]) -> float:
    dot    = sum(x * y for x, y in zip(a, b))
    norm_a = math.sqrt(sum(x * x for x in a))
    norm_b = math.sqrt(sum(x * x for x in b))
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return dot / (norm_a * norm_b)


# ---------------------------------------------------------------------------
# Jaccard similarity
# ---------------------------------------------------------------------------

def tokenize(text: str) -> list[str]:
    return [t for t in re.sub(r"[^a-z0-9\s]", " ", text.lower()).split() if t]


def bigrams(tokens: list[str]) -> list[tuple[str, str]]:
    return [(tokens[i], tokens[i + 1]) for i in range(len(tokens) - 1)]


def jaccard(a: set, b: set) -> float:
    if not a and not b:
        return 1.0
    union = a | b
    return len(a & b) / len(union) if union else 0.0


def jaccard_token(r1: dict, r2: dict) -> float:
    return jaccard(set(r1["tokens"]), set(r2["tokens"]))


def jaccard_bigram(r1: dict, r2: dict) -> float:
    return jaccard(set(r1["bigrams"]), set(r2["bigrams"]))


def attach_jaccard_fields(records: list[dict]) -> None:
    for r in records:
        toks = tokenize(r["response_text"])
        r["tokens"] = toks
        r["bigrams"] = bigrams(toks)


# ---------------------------------------------------------------------------
# Analysis
# ---------------------------------------------------------------------------

def mean_or_none(vals: list[float]) -> float | None:
    return statistics.mean(vals) if vals else None


def analyse(records: list[dict]) -> list[dict]:
    grouped: dict[int, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for r in records:
        grouped[r["prompt_index"]][r["dialect"]].append(r)

    prompt_rows = []
    for prompt_index in sorted(grouped):
        sae_runs  = sorted(grouped[prompt_index].get("SAE",  []), key=lambda x: x["trial"])
        aave_runs = sorted(grouped[prompt_index].get("AAVE", []), key=lambda x: x["trial"])
        category  = (sae_runs or aave_runs)[0]["category"]

        cos_within_sae:  list[float] = []
        cos_within_aave: list[float] = []
        cos_betw_match:  list[float] = []
        cos_betw_all:    list[float] = []

        tok_within_sae:  list[float] = []
        tok_within_aave: list[float] = []
        tok_betw_match:  list[float] = []
        tok_betw_all:    list[float] = []

        bi_within_sae:   list[float] = []
        bi_within_aave:  list[float] = []
        bi_betw_match:   list[float] = []
        bi_betw_all:     list[float] = []

        for l, r in itertools.combinations(sae_runs, 2):
            cos_within_sae.append(cosine(l["embedding"], r["embedding"]))
            tok_within_sae.append(jaccard_token(l, r))
            bi_within_sae.append(jaccard_bigram(l, r))

        for l, r in itertools.combinations(aave_runs, 2):
            cos_within_aave.append(cosine(l["embedding"], r["embedding"]))
            tok_within_aave.append(jaccard_token(l, r))
            bi_within_aave.append(jaccard_bigram(l, r))

        aave_by_trial = {r["trial"]: r for r in aave_runs}
        for sae_r in sae_runs:
            aave_r = aave_by_trial.get(sae_r["trial"])
            if aave_r:
                cos_betw_match.append(cosine(sae_r["embedding"], aave_r["embedding"]))
                tok_betw_match.append(jaccard_token(sae_r, aave_r))
                bi_betw_match.append(jaccard_bigram(sae_r, aave_r))

        for sae_r in sae_runs:
            for aave_r in aave_runs:
                cos_betw_all.append(cosine(sae_r["embedding"], aave_r["embedding"]))
                tok_betw_all.append(jaccard_token(sae_r, aave_r))
                bi_betw_all.append(jaccard_bigram(sae_r, aave_r))

        prompt_rows.append({
            "prompt_index":      prompt_index,
            "category":          category,
            "n_sae_trials":      len(sae_runs),
            "n_aave_trials":     len(aave_runs),
            # cosine — per-prompt means and raw lists for pooled t-test
            "cos_within_sae":    mean_or_none(cos_within_sae),
            "cos_within_aave":   mean_or_none(cos_within_aave),
            "cos_betw_match":    mean_or_none(cos_betw_match),
            "cos_betw_all":      mean_or_none(cos_betw_all),
            "_cos_within_sae":   cos_within_sae,
            "_cos_betw_match":   cos_betw_match,
            # token jaccard
            "tok_within_sae":    mean_or_none(tok_within_sae),
            "tok_within_aave":   mean_or_none(tok_within_aave),
            "tok_betw_match":    mean_or_none(tok_betw_match),
            "tok_betw_all":      mean_or_none(tok_betw_all),
            "_tok_within_sae":   tok_within_sae,
            "_tok_betw_match":   tok_betw_match,
            # bigram jaccard
            "bi_within_sae":     mean_or_none(bi_within_sae),
            "bi_within_aave":    mean_or_none(bi_within_aave),
            "bi_betw_match":     mean_or_none(bi_betw_match),
            "bi_betw_all":       mean_or_none(bi_betw_all),
            "_bi_within_sae":    bi_within_sae,
            "_bi_betw_match":    bi_betw_match,
        })
    return prompt_rows


