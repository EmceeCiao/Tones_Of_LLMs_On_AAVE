#!/usr/bin/env python3
"""
repeated_runs_similarity.py

Computes within-dialect vs between-dialect similarity across 5 repeated runs
of the base gpt-4.1 model (no system prompt) on the 15 Round 1 prompts.

Two independent measures are computed side by side:
  Cosine similarity  — semantic similarity via text-embedding-3-large
  Jaccard similarity — lexical overlap (token-level and bigram-level)

Having both matters: if within-dialect > between-dialect on BOTH measures,
you have two independent lines of evidence that the gap is caused by dialect
and not by the embedding model or temperature variation.

Measurements per prompt (for each metric):
  within_sae      — mean over all pairs of SAE trials (10 pairs for 5 trials)
  within_aave     — mean over all pairs of AAVE trials
  between_matched — SAE trial k vs AAVE trial k (5 matched pairs)
  between_all     — every SAE trial vs every AAVE trial (25 pairs)

Key number: dialect gap = within_sae - between_matched
  > 0.05 on cosine  → dialect effect exceeds temperature noise
  > 0.03 on token J → lexically confirmed (embedding-independent)

Reads from:
    Final_Dataset/study_logs/round1_repeated_runs.jsonl
    (generated by collect_round1_repeated_runs.py)

Output:
    Final_Dataset/round1_repeated_runs_similarity.xlsx
    Printed tables to stdout

Usage:
    export OPENAI_API_KEY="your-key"
    python scripts/repeated_runs_similarity.py
"""

